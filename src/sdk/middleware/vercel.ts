import type { DirghaGate } from '../gate.js';

/**
 * Middleware adapter for the Vercel AI SDK (ai / @ai-sdk/provider)
 *
 * Usage:
 * ```typescript
 * import { wrapLanguageModel } from 'ai';
 * import { openai } from '@ai-sdk/openai';
 * import { DirghaGate, createVercelAIMiddleware } from '@dirgha/sdk';
 *
 * const gate = new DirghaGate({ mode: 'strict' });
 * const safeModel = wrapLanguageModel({
 *   model: openai('gpt-4o'),
 *   middleware: createVercelAIMiddleware(gate),
 * });
 * ```
 */
export function createVercelAIMiddleware(gate: DirghaGate) {
  return {
    transformParams: async ({ params }: { params: { tools?: Array<{ name: string; description?: string; parameters?: unknown }> } }) => {
      // Filter out forbidden tools from model context
      if (!params.tools) return params;

      const filteredTools = [];
      for (const tool of params.tools) {
        const decision = await gate.evaluate(tool.name, {});
        // Allow in prompt if not hard-refused by allowlist
        if (decision.rule !== 5) {
          filteredTools.push(tool);
        }
      }

      return {
        ...params,
        tools: filteredTools,
      };
    },

    wrapGenerate: async ({ doGenerate, params }: { doGenerate: () => Promise<any>; params: any }) => {
      const result = await doGenerate();
      // Inspect tool calls generated by the model
      if (result.toolCalls && Array.isArray(result.toolCalls)) {
        for (const call of result.toolCalls) {
          const decision = await gate.evaluate(call.toolName, call.args || {});
          if (!decision.allowed) {
            throw new Error(`[LOKAHI GATE REFUSAL]: ${decision.reason}`);
          }
        }
      }
      return result;
    },
  };
}
